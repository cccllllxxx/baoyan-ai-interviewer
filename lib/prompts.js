function buildResumeSection(resume, target) {
  const r = (resume || "").trim();
  const t = (target || "").trim();
  if (!r) {
    return `目标方向：${t || "未填写"}

（考生未提供个人陈述，请围绕人文社科经管方向的一般性问题提问：研究兴趣、方法论基础、近期关注的行业或政策议题。）`;
  }
  return `目标方向：${t || "未填写"}

以下是考生提交的个人陈述 / 简历内容：
"""
${r.slice(0, 6000)}
"""

请先在心里标记出这份材料里**最虚的三处**：
- 说不清个人贡献的（「参与」「协助」「负责」但没有具体动作与产出）
- 没有量化、没有反例、没有边界条件的断言
- 一听就是模板话术的动机陈述（「对该方向有浓厚兴趣」「希望继续深造」）

这三处就是你本场面试的重点攻击对象。`;
}

